export const freeLabClient=[
"'use strict';",
'(function(){',
' const $=id=>document.getElementById(id);',
' let history=[];let turns=0;let busy=false;',
' function addMessage(role,text){',
'  const empty=$("empty");if(empty)empty.remove();',
'  const el=document.createElement("div");',
'  el.className="bubble "+(role==="user"?"user":"assistant");',
'  const title=document.createElement("strong");',
'  title.textContent=role==="user"?"Tu: ":"Assistente: ";',
'  const span=document.createElement("span");span.textContent=text;',
'  el.append(title,span);$("messages").appendChild(el);',
' }',
' function update(){',
'  $("send").disabled=busy||turns>=4;',
'  $("reset").disabled=busy;',
'  $("question").disabled=busy||turns>=4;',
'  if(turns>=4)$("status").textContent="Quattro turni completati. Per continuare, avvia una nuova conversazione.";',
' }',
' async function send(){',
'  if(busy||turns>=4)return;',
'  const question=$("question").value.trim();',
'  if(!question||question.length>400){$("status").textContent="Inserisci una domanda di massimo 400 caratteri.";return;}',
'  busy=true;update();$("status").textContent="In attesa del modello…";',
'  try{',
'   const r=await fetch("/api/lab/ai-free",{',
'    method:"POST",credentials:"same-origin",',
'    headers:{"Content-Type":"application/json"},',
'    body:JSON.stringify({question,history})',
'   });',
'   const data=await r.json();',
'   $("status").textContent=(data.decision||"ERRORE")+" — "+(data.message||"")',
'    +(data.diagnosticCode?" · Diagnostica: "+data.diagnosticCode:"")',
'    +" · Chiamate modello: "+String(data.modelRequests??0);',
'   if(r.ok&&data.decision==="FREE_CHAT_READY"&&typeof data.answer==="string"){',
'    addMessage("user",question);addMessage("assistant",data.answer);',
'    history.push({role:"user",content:question},{role:"assistant",content:data.answer});',
'    turns++;',
'    $("question").value="";',
'   }',
'  }catch(_){$("status").textContent="Connessione non disponibile.";}',
'  finally{busy=false;update();}',
' }',
' $("send").addEventListener("click",send);',
' $("question").addEventListener("keydown",e=>{',
'  if(e.key==="Enter"&&!e.shiftKey){e.preventDefault();send();}',
' });',
' $("reset").addEventListener("click",()=>{',
'  if(busy)return;history=[];turns=0;',
'  $("messages").replaceChildren();',
'  const p=document.createElement("p");p.id="empty";p.textContent="Nessun messaggio.";',
'  $("messages").appendChild(p);$("question").value="";',
'  $("status").textContent="Nuova conversazione. Nessuno storico precedente inviato.";',
'  update();',
' });',
' update();',
'})();'
].join('\n');
